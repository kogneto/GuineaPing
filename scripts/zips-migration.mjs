// Builds migrations/0003_zips.sql from the US Census Gazetteer ZCTA file (public domain):
// https://www2.census.gov/geo/docs/maps-data/data/gazetteer/2024_Gazetteer/2024_Gaz_zcta_national.zip
//   node scripts/zips-migration.mjs path/to/2024_Gaz_zcta_national.txt
// Every value is checked before it goes into SQL; anything unexpected stops the script.
import { readFileSync, writeFileSync } from "node:fs";

const [, , source] = process.argv;
if (!source) throw new Error("Pass the path to 2024_Gaz_zcta_national.txt");
const lines = readFileSync(source, "utf8").trim().split(/\r?\n/);
const header = lines.shift().split("\t").map((h) => h.trim());
const iZip = header.indexOf("GEOID"), iLat = header.indexOf("INTPTLAT"), iLon = header.indexOf("INTPTLONG");
if (iZip < 0 || iLat < 0 || iLon < 0) throw new Error(`Unexpected header: ${header.join(",")}`);

const rows = lines.map((line, n) => {
  const f = line.split("\t").map((s) => s.trim());
  const zip = f[iZip], lat = Number(f[iLat]), lon = Number(f[iLon]);
  if (!/^\d{5}$/.test(zip) || !(lat >= -90 && lat <= 90) || !(lon >= -180 && lon <= 180)) throw new Error(`Bad row ${n + 2}: ${line}`);
  return `('${zip}',${lat.toFixed(5)},${lon.toFixed(5)})`;
});

const chunks = [];
for (let i = 0; i < rows.length; i += 500) chunks.push(`INSERT INTO zips (zip, lat, lon) VALUES\n${rows.slice(i, i + 500).join(",\n")};`);
writeFileSync(
  "migrations/0003_zips.sql",
  `-- US ZIP code (ZCTA) centre points, from the US Census Bureau 2024 Gazetteer (public domain).
-- Generated by scripts/zips-migration.mjs; used to turn a Watch's ZIP code into a point for
-- ClinicalTrials.gov's distance search.
CREATE TABLE zips (zip TEXT PRIMARY KEY, lat REAL NOT NULL, lon REAL NOT NULL) WITHOUT ROWID;
${chunks.join("\n")}
`,
);
console.log(`Wrote ${rows.length} ZIP codes in ${chunks.length} statements.`);
